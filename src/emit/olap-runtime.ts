// The ClickHouse adapter a generated service carries (B95.3). It is plain
// JavaScript emitted next to the bodies, so the service stays dependency-free
// and the compiler owns the table shape: every column name comes from the
// declared record, and every value travels as a {pN:Type} parameter, never as
// string interpolation.
//
// Two rules decide the behaviour:
//  - an entity the model does not declare, or a column outside its record, is
//    an Invalid error before a byte leaves the service — a ClickHouse 400 in
//    its own words is not something a body author can act on;
//  - append is at-least-once (a retried job writes the row twice), which is
//    why a metric that must not inflate asks for distinct.
import type { OlapTable } from './olap.ts';

function tableLiteral(tables: OlapTable[]): string {
  if (tables.length === 0) return '{}';
  const entries = tables.map((table) =>
    JSON.stringify(table.name) + ': [' + table.columns.map((column) => '[' + JSON.stringify(column.name) + ', ' + JSON.stringify(column.type) + ']').join(', ') + ']',
  );
  return '{ ' + entries.join(', ') + ' }';
}

export function olapRuntime(tables: OlapTable[]): string {
  return [
    '// ---------- olap (ClickHouse over HTTP 8123) ----------',
    '',
    "const OLAP_URL = String(process.env.CLICKHOUSE_URL || process.env.OLAP_URL || '').replace(/\\/+$/, '');",
    "const OLAP_USER = process.env.CLICKHOUSE_USER || '';",
    "const OLAP_PASSWORD = process.env.CLICKHOUSE_PASSWORD || '';",
    'const OLAP_TIMEOUT_MS = Number(process.env.OLAP_TIMEOUT_MS || 15000);',
    'const OLAP_TABLES = ' + tableLiteral(tables) + ';',
    '',
    'function olapError(kind, message) {',
    '  const error = new Error(message);',
    '  error.error = kind;',
    '  return error;',
    '}',
    '',
    'function olapQuote(name) {',
    "  return '\"' + String(name).replace(/\"/g, '') + '\"';",
    '}',
    '',
    '// A table the model never declared has no columns to check against, so a',
    '// body naming it is asking for a store the service does not have.',
    'function olapTable(entity) {',
    '  const key = entity === undefined || entity === null ? "" : String(entity);',
    '  if (!Object.prototype.hasOwnProperty.call(OLAP_TABLES, key)) {',
    '    const known = Object.keys(OLAP_TABLES);',
    '    throw olapError("Invalid", "olap: table " + JSON.stringify(key) + " is not declared; declared: " + (known.length > 0 ? known.join(", ") : "none"));',
    '  }',
    '  return OLAP_TABLES[key];',
    '}',
    '',
    'async function olapRequest(sql, body, params) {',
    '  if (!OLAP_URL) throw olapError("Unavailable", "olap: CLICKHOUSE_URL is not set");',
    '  const query = new URLSearchParams();',
    '  for (const [key, value] of Object.entries(params || {})) query.set("param_" + key, String(value));',
    '  query.set("query", String(sql));',
    '  const search = query.toString();',
    '  const url = OLAP_URL + "/" + (search ? "?" + search : "");',
    '  const controller = new AbortController();',
    '  const timer = setTimeout(() => controller.abort(), OLAP_TIMEOUT_MS);',
    '  try {',
    '    const headers = {};',
    '    if (OLAP_USER) headers["x-clickhouse-user"] = OLAP_USER;',
    '    if (OLAP_PASSWORD) headers["x-clickhouse-key"] = OLAP_PASSWORD;',
    '    const init = { method: "POST", signal: controller.signal, headers };',
    '    if (body !== undefined && body !== null) init.body = body;',
    '    const response = await fetch(url, init);',
    '    const text = await response.text();',
    '    if (!response.ok) throw olapError("Unavailable", "olap: ClickHouse answered " + response.status + ": " + text.slice(0, 300));',
    '    return text;',
    '  } catch (error) {',
    '    if (error && error.error) throw error;',
    '    if (error && error.name === "AbortError") throw olapError("Unavailable", "olap: timeout after " + OLAP_TIMEOUT_MS + "ms");',
    '    throw olapError("Unavailable", "olap: " + String(error && error.message ? error.message : error));',
    '  } finally {',
    '    clearTimeout(timer);',
    '  }',
    '}',
    '',
    '// One record, checked against the declared columns: an unknown key is a typo',
    '// that ClickHouse would drop silently or reject in its own words, and a',
    '// missing non-nullable column is the same mistake in the other direction.',
    'function olapRow(entity, record) {',
    '  const columns = olapTable(entity);',
    '  if (record === null || typeof record !== "object" || Array.isArray(record)) {',
    '    throw olapError("Invalid", "olap: the record for " + entity + " must be an object");',
    '  }',
    '  const known = new Set(columns.map((column) => column[0]));',
    '  for (const key of Object.keys(record)) {',
    '    if (!known.has(key)) throw olapError("Invalid", "olap: column " + JSON.stringify(key) + " does not exist on " + entity + "; declared: " + columns.map((column) => column[0]).join(", "));',
    '  }',
    '  const row = {};',
    '  for (const [name, type] of columns) {',
    '    const value = record[name];',
    '    if (value === undefined || value === null) {',
    '      if (String(type).startsWith("Nullable(")) { row[name] = null; continue; }',
    '      throw olapError("Invalid", "olap: column " + JSON.stringify(name) + " of " + entity + " has no value and is not nullable");',
    '    }',
    '    row[name] = value;',
    '  }',
    '  return row;',
    '}',
    '',
    'async function olapAppend(entity, record) {',
    '  const row = olapRow(entity, record);',
    '  await olapRequest("INSERT INTO " + olapQuote(entity) + " FORMAT JSONEachRow", JSON.stringify(row) + "\\n", {});',
    '}',
    '',
    'const OLAP_METRICS = new Set(["sum", "count", "avg", "min", "max"]);',
    'const OLAP_OPERATORS = new Set(["gt", "gte", "lt", "lte", "ne", "in", "contains"]);',
    'const OLAP_SYMBOLS = { gt: ">", gte: ">=", lt: "<", lte: "<=", ne: "!=" };',
    '',
    '// A typed select is built from the declared columns, so a name the body',
    '// invented fails here with the list of what exists instead of after the query.',
    'function olapSelectSql(table, columns, query) {',
    '  const byName = new Map(columns.map((column) => [column[0], column]));',
    '  const params = {};',
    '  let counter = 0;',
    '  const columnOf = (name) => {',
    '    const column = byName.get(name);',
    '    if (!column) throw olapError("Invalid", "olap: unknown column " + JSON.stringify(name) + " on " + table + "; declared: " + columns.map((item) => item[0]).join(", "));',
    '    return column;',
    '  };',
    '  const param = (value, type) => {',
    '    counter += 1;',
    '    const key = "p" + counter;',
    '    params[key] = value === null || value === undefined ? "" : String(value);',
    '    return "{" + key + ":" + type + "}";',
    '  };',
    '',
    '  const conditions = [];',
    '  const where = query.where && typeof query.where === "object" && !Array.isArray(query.where) ? query.where : {};',
    '  for (const [name, raw] of Object.entries(where)) {',
    '    const column = columnOf(name);',
    '    const ref = olapQuote(column[0]);',
    '    if (raw !== null && typeof raw === "object" && !Array.isArray(raw)) {',
    '      for (const [operator, value] of Object.entries(raw)) {',
    '        if (!OLAP_OPERATORS.has(operator)) throw olapError("Invalid", "olap: unknown operator " + operator + " on column " + name + "; use gt, gte, lt, lte, ne, in or contains");',
    '        if (operator === "in") {',
    '          const list = Array.isArray(value) ? value : [value];',
    '          if (list.length === 0) { conditions.push("0"); continue; }',
    '          conditions.push(ref + " IN (" + list.map((item) => param(item, column[1])).join(", ") + ")");',
    '          continue;',
    '        }',
    '        if (operator === "contains") {',
    '          conditions.push("position(" + ref + ", " + param(value, column[1]) + ") > 0");',
    '          continue;',
    '        }',
    '        conditions.push(ref + " " + OLAP_SYMBOLS[operator] + " " + param(value, column[1]));',
    '      }',
    '      continue;',
    '    }',
    '    if (raw === null) { conditions.push(ref + " IS NULL"); continue; }',
    '    conditions.push(ref + " = " + param(raw, column[1]));',
    '  }',
    '',
    '  const group = (Array.isArray(query.groupBy) ? query.groupBy : []).map((name) => olapQuote(columnOf(name)[0]));',
    '  const metrics = (Array.isArray(query.metrics) ? query.metrics : []).map((metric) => {',
    '    const op = String(metric && metric.op ? metric.op : "").toLowerCase();',
    '    if (!OLAP_METRICS.has(op)) throw olapError("Invalid", "olap: unknown metric " + JSON.stringify(metric && metric.op) + "; use sum, count, avg, min or max");',
    '    const alias = metric && metric.name ? String(metric.name) : op;',
    '    if (op === "count" && (!metric.field || metric.distinct)) {',
    '      const field = metric.distinct ? columnOf(metric.field || "")[0] : null;',
    '      return "count(" + (field ? "DISTINCT " + olapQuote(field) : "*") + ") AS " + olapQuote(alias);',
    '    }',
    '    const field = columnOf(metric.field || metric.name);',
    '    return op + "(" + olapQuote(field[0]) + ") AS " + olapQuote(alias);',
    '  });',
    '',
    '  const list = group.concat(metrics);',
    '  const sql = ["SELECT " + (list.length > 0 ? list.join(", ") : "*"), "FROM " + olapQuote(table)];',
    '  if (conditions.length > 0) sql.push("WHERE " + conditions.join(" AND "));',
    '  if (group.length > 0) sql.push("GROUP BY " + group.join(", "));',
    '  if (query.order) {',
    '    const parts = String(query.order).trim().split(/\\s+/);',
    '    const column = columnOf(parts[0]);',
    '    sql.push("ORDER BY " + olapQuote(column[0]) + " " + (String(parts[1] || "asc").toLowerCase() === "desc" ? "DESC" : "ASC"));',
    '  }',
    '  if (query.limit !== undefined && query.limit !== null) {',
    '    const limit = Math.trunc(Number(query.limit));',
    '    if (!Number.isFinite(limit) || limit <= 0) throw olapError("Invalid", "olap: limit must be a positive whole number");',
    '    sql.push("LIMIT " + limit);',
    '  }',
    '  sql.push("FORMAT JSON");',
    '  return { sql: sql.join("\\n"), params };',
    '}',
    '',
    'async function olapSelect(entity, query) {',
    '  const columns = olapTable(entity);',
    '  const built = olapSelectSql(String(entity), columns, query && typeof query === "object" ? query : {});',
    '  const text = await olapRequest(built.sql, undefined, built.params);',
    '  let parsed = null;',
    '  try { parsed = JSON.parse(text); } catch (error) {',
    '    throw olapError("Unavailable", "olap: ClickHouse answered something other than JSON");',
    '  }',
    '  return parsed && Array.isArray(parsed.data) ? parsed.data : [];',
    '}',
    '',
    '// The raw escape hatch: one read-only statement. A second one could hide a',
    '// write behind a SELECT, and a value interpolated into the text is an',
    '// injection the typed select exists to prevent.',
    'async function olapSql(sql, params) {',
    '  const trimmed = String(sql === undefined || sql === null ? "" : sql).trim().replace(/;+$/, "");',
    '  if (trimmed.includes(";") || !/^(select|with)\\b/i.test(trimmed)) {',
    '    throw olapError("Invalid", "olap: raw sql accepts one read-only statement (SELECT or WITH)");',
    '  }',
    '  const text = await olapRequest(trimmed, undefined, params && typeof params === "object" ? params : {});',
    '  let parsed = null;',
    '  try { parsed = JSON.parse(text); } catch (error) { return []; }',
    '  return parsed && Array.isArray(parsed.data) ? parsed.data : [];',
    '}',
    '',
    'async function olapPing() {',
    '  await olapRequest("SELECT 1", undefined, {});',
    '}',
    '',
  ].join('\n');
}
