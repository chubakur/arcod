#!/usr/bin/env node
// Quality harness for the local model: take the reference specs, generate every
// body with the model, run the spec's own examples against the generated
// service, and report what survived. The numbers answer one question: can a
// local model carry the project, or only the easy examples?
//
//   node scripts/model-harness.mjs [example ...]
//
// Offline: one SKIP line and exit 0 (see scripts/e2e-local-model.mjs for the
// same rule). With a model: writes docs/model-report.md and prints the table.

import { spawn } from 'node:child_process';
import { cp, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const arcod = join(root, 'bin', 'arcod.mjs');
const endpoint = process.env.OLLAMA_ENDPOINT || 'http://localhost:11434';
const model = process.env.ARC_MODEL || 'qwen2.5-coder:7b';
const wanted = process.argv.slice(2);

async function reachable(url) {
  try {
    const response = await fetch(url + '/api/tags', { signal: AbortSignal.timeout(2000) });
    return response.ok;
  } catch {
    return false;
  }
}

if (!(await reachable(endpoint))) {
  process.stdout.write('SKIP model-harness: Ollama is not reachable at ' + endpoint + ' — set OLLAMA_ENDPOINT.\n');
  process.exit(0);
}

function run(args, cwd) {
  return new Promise((resolve) => {
    const started = Date.now();
    const child = spawn(process.execPath, [arcod, ...args], { cwd, env: process.env });
    let out = '';
    child.stdout.on('data', (chunk) => {
      out += chunk;
    });
    child.stderr.on('data', (chunk) => {
      out += chunk;
    });
    child.on('close', (code) => resolve({ code: code ?? 1, out, ms: Date.now() - started }));
  });
}

const examplesDir = join(root, 'examples');
const names = (await readdir(examplesDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => wanted.length === 0 || wanted.includes(name));

const rows = [];
const dir = await mkdtemp(join(tmpdir(), 'arcod-harness-'));
try {
  for (const name of names) {
    const source = join(examplesDir, name);
    const specPath = join(source, 'main.arc');
    let spec;
    try {
      spec = await readFile(specPath, 'utf8');
    } catch {
      continue;
    }
    const ops = (spec.match(/^\s+(?:public\s+)?op\s+[a-zA-Z_]/gm) || []).length;
    // Work on a copy: generation must not touch the checked-in impl/ bodies.
    const work = join(dir, name);
    await cp(source, work, { recursive: true });
    await rm(join(work, 'impl'), { recursive: true, force: true });

    const impl = await run(['impl', '.', '--endpoint', endpoint, '--model', model], work);
    const generated = (await readdir(join(work, 'impl')).catch(() => []))
      .filter((file) => file.endsWith('.mjs')).length;
    const tests = impl.code === 0
      ? await run(['test', '.', '--impl'], work)
      : { code: 1, out: '', ms: 0 };
    const examplesRun = (tests.out.match(/^\s*(✔|✖)\s/gm) || []).length;
    const examplesOk = (tests.out.match(/^\s*✔\s/gm) || []).length;

    rows.push({
      example: name,
      ops,
      generated,
      coverage: ops === 0 ? 0 : generated / ops,
      examplesRun,
      examplesOk,
      contract: tests.code === 0,
      implMs: impl.ms,
      testMs: tests.ms,
    });
    process.stdout.write(
      name + ': ' + generated + '/' + ops + ' bodies, ' +
        examplesOk + '/' + examplesRun + ' examples, ' + (tests.code === 0 ? 'green' : 'red') + '\n',
    );
  }
} finally {
  await rm(dir, { recursive: true, force: true });
}

const totalOps = rows.reduce((sum, row) => sum + row.ops, 0);
const totalGenerated = rows.reduce((sum, row) => sum + row.generated, 0);
const green = rows.filter((row) => row.contract).length;
const report = [
  '# Local model report',
  '',
  'Model ' + model + ', endpoint ' + endpoint + ', ' + new Date().toISOString(),
  '',
  'Coverage: ' + totalGenerated + '/' + totalOps + ' bodies generated (' +
    Math.round((totalOps ? totalGenerated / totalOps : 0) * 100) + '%).',
  'Contract: ' + green + '/' + rows.length + ' examples pass their own examples.',
  '',
  '| example | bodies | examples | green | impl s | test s |',
  '|---|---|---|---|---|---|',
  ...rows.map((row) => '| ' + row.example + ' | ' + row.generated + '/' + row.ops + ' | ' +
    row.examplesOk + '/' + row.examplesRun + ' | ' + (row.contract ? 'yes' : 'no') + ' | ' +
    (row.implMs / 1000).toFixed(1) + ' | ' + (row.testMs / 1000).toFixed(1) + ' |'),
  '',
  'Generated by scripts/model-harness.mjs. Bodies are generated into a temp',
  'copy, never into the repository; the checked-in impl/ files stay as they were.',
  '',
].join('\n');

await writeFile(join(root, 'docs', 'model-report.md'), report);
process.stdout.write('\n' + report);
